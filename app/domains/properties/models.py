# app/domains/properties/models.py

"""
Domain: Properties
Tables: properties, property_features, property_feature_map
Enums: PropertyType, ListingStatus, ApprovalStatus, FeatureCategory

Design decisions:
  - Amenities are rows, not boolean columns (Decision 7).
    Adding "Rooftop Terrace" = INSERT one row, zero schema changes.
  - ListingStatus (rent/sale/short_let/lease) is separate from ApprovalStatus.
    ListingStatus = what the listing is FOR (never changes after creation).
    ApprovalStatus = the listing's LIFECYCLE (changes through state machine).
  - Only approval_status = 'published' AND expires_at > now() is public (Rule 2).
  - address_hidden = True means only city/state shown publicly (Decision 10).
  - expires_at is set to now() + 30 days when published (Decision 4).
  - latitude/longitude are NOT NULL — every property needs coordinates for search.
  - price uses Numeric(15,2) — exact decimal, no floating-point rounding.
  - All CHECK constraints from SQL schema v9.2 are re-declared here so
    Alembic detects them and includes them in autogenerated migrations.
  - hybrid_property used for computed properties that appear in queries.
    @property used for display-only computed properties.
"""

