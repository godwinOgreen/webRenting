# ─── Enums ───────────────────────────────────────────────────────────────────

class PropertyType(str, enum.Enum):
    """Physical type of the property."""
    APARTMENT = "apartment"
    HOUSE = "house"
    DUPLEX = "duplex"
    STUDIO = "studio"
    COMMERCIAL = "commercial"
    OFFICE = "office"


class ListingStatus(str, enum.Enum):
    """
    What the agent is offering the property for.
    Set at creation time. Does not change through the approval lifecycle.
    """
    RENT = "rent"
    SALE = "sale"
    SHORT_LET = "short_let"
    LEASE = "lease"


class ApprovalStatus(str, enum.Enum):
    """
    Full property lifecycle state machine.

    10 states, 19 valid transitions.
    Only PUBLISHED + not expired = appears in public search (Rule 2).

    States:
      DRAFT          — agent editing, never submitted
      PENDING_REVIEW — submitted, admin hasn't decided yet
      APPROVED       — admin approved, agent can publish
      REJECTED       — admin rejected, never was public
      PUBLISHED      — live, appears in search
      RESERVED       — agent reserved for a specific renter
      RENTED         — tenancy active, no longer available
      SOLD           — sold (for sale listings)
      ARCHIVED       — expired or manually archived
      SUSPENDED      — admin pulled a published listing offline

    Removed from ERD v9.2:
      EXPIRED  — use ARCHIVED instead (Celery sets ARCHIVED when expires_at passes)
      FLAGGED  — handled by reports table + admin action (not a property state)

    Valid transitions (enforced in property_service.py):
      DRAFT           → PENDING_REVIEW  (agent submits)
      PENDING_REVIEW  → APPROVED        (admin approves)
      PENDING_REVIEW  → REJECTED        (admin rejects)
      REJECTED        → PENDING_REVIEW  (agent resubmits after fixing)
      APPROVED        → PUBLISHED       (agent publishes)
      APPROVED        → DRAFT           (agent edits before publishing)
      PUBLISHED       → RESERVED        (agent marks reserved)
      PUBLISHED       → RENTED          (agent marks rented directly)
      PUBLISHED       → SOLD            (agent marks sold)
      PUBLISHED       → ARCHIVED        (Celery: expires_at passed)
      PUBLISHED       → PENDING_REVIEW  (agent edits published listing)
      PUBLISHED       → SUSPENDED       (admin pulls offline)
      RESERVED        → RENTED          (tenancy confirmed)
      RESERVED        → PUBLISHED       (reservation falls through)
      RENTED          → ARCHIVED        (auto-archived)
      SOLD            → ARCHIVED        (auto-archived)
      SUSPENDED       → PUBLISHED       (admin re-enables)
      SUSPENDED       → ARCHIVED        (admin archives)
      ARCHIVED        → PENDING_REVIEW  (agent republishes)
    """
    DRAFT = "draft"
    PENDING_REVIEW = "pending_review"
    APPROVED = "approved"
    REJECTED = "rejected"
    PUBLISHED = "published"
    RESERVED = "reserved"
    RENTED = "rented"
    SOLD = "sold"
    ARCHIVED = "archived"
    SUSPENDED = "suspended"


class FeatureCategory(str, enum.Enum):
    """
    Groups features for UI display and search filtering.

    Seed data (in Alembic migration):
      amenities → Furnished, Air Conditioning, Generator, Water Supply, Parking
      rules     → Pet Allowed, No Smoking, Family Only, Female Only
      building  → Balcony, Garden, Elevator, Swimming Pool, Gym
      security  → Security Guard, CCTV, Gated Estate, Intercom
    """
    AMENITIES = "amenities"
    RULES = "rules"
    BUILDING = "building"
    SECURITY = "security"


